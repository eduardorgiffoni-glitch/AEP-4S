-- Descarte Point | MySQL 8.x
CREATE DATABASE IF NOT EXISTS descarte_point CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE descarte_point;
CREATE TABLE IF NOT EXISTS usuarios (
 id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL, email VARCHAR(100) NOT NULL UNIQUE,
 senha VARCHAR(255) NOT NULL, tipo_usuario ENUM('ADMINISTRADOR','COMUM') NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS localizacoes (
 id INT AUTO_INCREMENT PRIMARY KEY, logradouro VARCHAR(100) NOT NULL, numero VARCHAR(20) NOT NULL,
 bairro VARCHAR(80) NOT NULL, cidade VARCHAR(80) NOT NULL, cep VARCHAR(12) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS pontos_descarte (
 id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL, horario_funcionamento VARCHAR(80) NOT NULL,
 usuario_id INT NULL, localizacao_id INT NOT NULL UNIQUE,
 CONSTRAINT fk_ponto_usuario FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 CONSTRAINT fk_ponto_local FOREIGN KEY(localizacao_id) REFERENCES localizacoes(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS residuos (
 id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL, descricao VARCHAR(255) NOT NULL,
 categoria ENUM('ELETRONICO','RECICLAVEL','PERIGOSO') NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS residuos_eletronicos (
 id INT PRIMARY KEY, tipo_equipamento VARCHAR(80) NOT NULL,
 CONSTRAINT fk_eletronico FOREIGN KEY(id) REFERENCES residuos(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS residuos_reciclaveis (
 id INT PRIMARY KEY, material VARCHAR(80) NOT NULL,
 CONSTRAINT fk_reciclavel FOREIGN KEY(id) REFERENCES residuos(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS residuos_perigosos (
 id INT PRIMARY KEY, risco VARCHAR(80) NOT NULL,
 CONSTRAINT fk_perigoso FOREIGN KEY(id) REFERENCES residuos(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ponto_residuo (
 ponto_id INT NOT NULL, residuo_id INT NOT NULL, data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(ponto_id,residuo_id),
 CONSTRAINT fk_pr_ponto FOREIGN KEY(ponto_id) REFERENCES pontos_descarte(id) ON DELETE CASCADE,
 CONSTRAINT fk_pr_residuo FOREIGN KEY(residuo_id) REFERENCES residuos(id) ON DELETE CASCADE
) ENGINE=InnoDB;